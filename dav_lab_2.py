# Extract the date part for daily aggregation
df['date'] = df['date_time'].dt.date

# Calculate the daily average magnitude
daily_avg_magnitude = df.groupby('date')['magnitude'].mean().reset_index()

# Convert 'date' back to datetime for plotting
daily_avg_magnitude['date'] = pd.to_datetime(daily_avg_magnitude['date'])

plt.figure(figsize=(12, 7))
sns.lineplot(data=daily_avg_magnitude, x='date', y='magnitude')
plt.title('Daily Average Earthquake Magnitude Over Time')
plt.xlabel('Date')
plt.ylabel('Average Magnitude')
plt.grid(True, linestyle='--', alpha=0.7)
plt.tight_layout()
plt.show()

