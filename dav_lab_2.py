"""This pie chart illustrates the proportional distribution of different earthquake magnitude types found in the dataset. Each slice represents a `magType`, and its size corresponds to its percentage of the total number of earthquakes, providing a clear visual summary of their relative frequencies.

This histogram shows the frequency of earthquakes across different magnitude ranges. The `kde=True` argument adds a Kernel Density Estimate plot, which provides a smoothed representation of the distribution.
"""

plt.figure(figsize=(10, 8))
plt.pie(earthquakes_by_country.values, labels=earthquakes_by_country.index, autopct='%1.1f%%', startangle=90, wedgeprops={'edgecolor': 'black'})
